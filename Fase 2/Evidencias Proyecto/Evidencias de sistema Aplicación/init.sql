CREATE FUNCTION public.emergen_validar_plan_usuario() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE v_padre integer; v_ocupados integer;
BEGIN
    IF TG_OP = 'DELETE' OR (TG_OP = 'UPDATE' AND OLD.usuario_id IS DISTINCT FROM NEW.usuario_id) THEN
        PERFORM public.emergen_bloquear_usuario(OLD.usuario_id);
        IF EXISTS (SELECT 1 FROM public.usuario WHERE usuario_principal_id = OLD.usuario_id) THEN
            RAISE EXCEPTION 'No se puede retirar el plan mientras existan apadrinados vinculados' USING ERRCODE = '23514';
        END IF;
        IF EXISTS (SELECT 1 FROM public.reserva_cupos WHERE usuario_id=OLD.usuario_id AND estado IN ('RESERVADA','CREANDO','CAPTURANDO','INCIERTA')) THEN
            RAISE EXCEPTION 'Conciliar reservas antes de retirar el plan' USING ERRCODE='23514';
        END IF;
        IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    END IF;
    PERFORM public.emergen_bloquear_usuario(NEW.usuario_id);
    IF TG_OP = 'UPDATE' AND NEW.plan_id <> OLD.plan_id AND EXISTS (SELECT 1 FROM public.reserva_cupos WHERE usuario_id=OLD.usuario_id AND estado IN ('RESERVADA','CREANDO','CAPTURANDO','INCIERTA')) THEN
        RAISE EXCEPTION 'Conciliar reservas antes de cambiar el plan' USING ERRCODE='23514';
    END IF;
    SELECT usuario_principal_id INTO v_padre FROM public.usuario WHERE usuario_id = NEW.usuario_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Usuario del plan inexistente' USING ERRCODE = '23503'; END IF;
    IF v_padre IS NOT NULL THEN RAISE EXCEPTION 'El plan pertenece al principal, no al apadrinado' USING ERRCODE = '23514'; END IF;
    SELECT count(*) INTO v_ocupados FROM public.usuario WHERE usuario_principal_id = NEW.usuario_id;
    IF NEW.cupos_apadrinados_adq + COALESCE((SELECT sum(cupos) FROM public.reserva_cupos WHERE usuario_id=NEW.usuario_id AND estado IN ('RESERVADA','CREANDO','CAPTURANDO','INCIERTA')),0) > 5 THEN
        RAISE EXCEPTION 'Capacidad y reservas superan cinco cupos' USING ERRCODE='23514';
    END IF;
    IF v_ocupados > NEW.cupos_apadrinados_adq THEN
        RAISE EXCEPTION 'No se pueden reducir cupos por debajo de los utilizados' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER emergen_plan_usuario BEFORE INSERT OR UPDATE OR DELETE ON public.plan_usuario
FOR EACH ROW EXECUTE FUNCTION public.emergen_validar_plan_usuario();

CREATE FUNCTION public.emergen_validar_contactos() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE v_total integer;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.usuario_id IS DISTINCT FROM OLD.usuario_id THEN
            RAISE EXCEPTION 'Un contacto pertenece a su perfil original; crear otro contacto para otro perfil' USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP = 'DELETE' THEN
        PERFORM public.emergen_bloquear_usuario(OLD.usuario_id);
        IF EXISTS (SELECT 1 FROM public.usuario WHERE usuario_id = OLD.usuario_id) THEN
            SELECT count(*) INTO v_total FROM public.contacto_emergencia WHERE usuario_id = OLD.usuario_id;
            IF v_total <= 1 THEN
                RAISE EXCEPTION 'Se debe conservar al menos un contacto; reemplazarlo antes de borrar el último' USING ERRCODE = '23514';
            END IF;
        END IF;
        RETURN OLD;
    END IF;
    PERFORM public.emergen_bloquear_usuario(NEW.usuario_id);
    SELECT count(*) INTO v_total FROM public.contacto_emergencia WHERE usuario_id = NEW.usuario_id;
    IF v_total >= 5 THEN RAISE EXCEPTION 'Máximo cinco contactos por perfil' USING ERRCODE = '23514'; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER emergen_contactos BEFORE INSERT OR UPDATE OF usuario_id OR DELETE ON public.contacto_emergencia
FOR EACH ROW EXECUTE FUNCTION public.emergen_validar_contactos();

