-- Borrado de cuenta: primero se cierran/desasocian sus eventos. No se borran
-- alertas por CASCADE. No crea una cuenta sustituta ni un principal ficticio.
CREATE FUNCTION public.emergen_preparar_borrado_usuario() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE r record; v_cierre timestamptz; v_ubicaciones integer[];
BEGIN
    IF EXISTS (SELECT 1 FROM public.usuario WHERE usuario_principal_id = OLD.usuario_id) THEN
        RAISE EXCEPTION 'Resolver los apadrinados antes de borrar al principal' USING ERRCODE = '23503';
    END IF;
    IF EXISTS (SELECT 1 FROM public.reserva_cupos WHERE usuario_id=OLD.usuario_id AND estado NOT IN ('APLICADA','LIBERADA')) THEN
        RAISE EXCEPTION 'Conciliar las compras pendientes antes de eliminar la cuenta' USING ERRCODE='23514';
    END IF;
    DELETE FROM public.reserva_cupos WHERE usuario_id=OLD.usuario_id;
    SELECT array_agg(ubicacion_alerta_id) INTO v_ubicaciones FROM public.alerta WHERE usuario_id = OLD.usuario_id AND ubicacion_alerta_id IS NOT NULL;
    FOR r IN SELECT * FROM public.alerta WHERE usuario_id = OLD.usuario_id FOR UPDATE LOOP
        IF r.estado_alerta = 'ACTIVA' THEN
            v_cierre := GREATEST(clock_timestamp(), r.fecha_creacion);
            UPDATE public.alerta SET estado_alerta = 'FINALIZADA', fecha_cierre = v_cierre WHERE alerta_id = r.alerta_id;
            INSERT INTO public.historial_alerta (alerta_id, detalle_alerta_id, estado_anterior, estado_actual, fecha_cambio_estado)
            VALUES (r.alerta_id, r.detalle_alerta_id, 'ACTIVA', 'FINALIZADA', v_cierre);
        END IF;
        UPDATE public.envio_alerta SET estado_envio_id = 3, fecha_envio = NULL WHERE alerta_id = r.alerta_id AND estado_envio_id = 1;
        UPDATE public.enlace_medico SET fecha_revocacion = COALESCE(fecha_revocacion, GREATEST(clock_timestamp(), fecha_generacion)) WHERE alerta_id = r.alerta_id;
        UPDATE public.detalle_alerta SET texto_mensaje = '[Contenido eliminado]', msj_personalizado_id = NULL, antecedente_medico_id = NULL WHERE detalle_alerta_id = r.detalle_alerta_id;
        UPDATE public.alerta SET ubicacion_alerta_id = NULL WHERE alerta_id = r.alerta_id;
    END LOOP;
    DELETE FROM public.ubicacion_alerta u WHERE u.ubicacion_alerta_id = ANY (v_ubicaciones)
      AND NOT EXISTS (SELECT 1 FROM public.alerta a WHERE a.ubicacion_alerta_id = u.ubicacion_alerta_id);
    -- BITACORA conserva sus filas y rol histórico; no acredita anonimización completa.
    -- Menciones a terceros en texto libre y mensajes de visitantes deben
    -- revisarse en backend; esta rutina no acredita anonimización completa.
    -- Bitácora conservada: actor y afectado se desasocian mediante sus FK SET NULL.
    UPDATE public.respuesta_contacto SET texto_respuesta = '[Contenido eliminado]' WHERE usuario_id = OLD.usuario_id;
    RETURN OLD;
END;
$$;
CREATE TRIGGER emergen_usuario_borrado BEFORE DELETE ON public.usuario
FOR EACH ROW EXECUTE FUNCTION public.emergen_preparar_borrado_usuario();

