CREATE FUNCTION public.emergen_validar_alerta() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE v_medico integer; v_mensaje integer; v_mensaje_usuario integer; v_principal integer;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.usuario_id IS DISTINCT FROM OLD.usuario_id AND NEW.usuario_id IS NOT NULL THEN
            RAISE EXCEPTION 'No se reasigna una alerta a otro emisor' USING ERRCODE = '23514';
        END IF;
        IF NEW.detalle_alerta_id IS DISTINCT FROM OLD.detalle_alerta_id OR NEW.fecha_creacion IS DISTINCT FROM OLD.fecha_creacion THEN
            RAISE EXCEPTION 'El detalle y la fecha de creación de una alerta son inmutables' USING ERRCODE = '23514';
        END IF;
        IF NEW.estado_alerta IS DISTINCT FROM OLD.estado_alerta AND OLD.estado_alerta <> 'ACTIVA' THEN
            RAISE EXCEPTION 'Una alerta terminada no se reactiva ni cambia a otro estado terminal' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.usuario_id IS NULL OR NEW.estado_alerta <> 'ACTIVA' THEN
            RAISE EXCEPTION 'Una alerta nueva requiere emisor y estado ACTIVA' USING ERRCODE = '23514';
        END IF;
        PERFORM public.emergen_bloquear_usuario(NEW.usuario_id);
        SELECT COALESCE(usuario_principal_id, usuario_id) INTO v_principal FROM public.usuario WHERE usuario_id = NEW.usuario_id;
        IF NOT EXISTS (SELECT 1 FROM public.plan_usuario WHERE usuario_id = v_principal) THEN
            RAISE EXCEPTION 'El emisor o su principal requiere un plan adquirido para SOS' USING ERRCODE = '23514';
        END IF;
        IF NOT EXISTS (SELECT 1 FROM public.contacto_emergencia WHERE usuario_id = NEW.usuario_id) THEN
            RAISE EXCEPTION 'Configurar un contacto antes de activar SOS' USING ERRCODE = '23514';
        END IF;
        SELECT d.antecedente_medico_id, d.msj_personalizado_id INTO v_medico, v_mensaje
        FROM public.detalle_alerta d WHERE d.detalle_alerta_id = NEW.detalle_alerta_id;
        IF v_medico IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.antecedente_medico WHERE antecedente_medico_id = v_medico AND usuario_id = NEW.usuario_id) THEN
            RAISE EXCEPTION 'Ficha médica de otro usuario' USING ERRCODE = '23514';
        END IF;
        SELECT msj_personalizado_id INTO v_mensaje_usuario FROM public.usuario WHERE usuario_id = NEW.usuario_id;
        IF v_mensaje IS NOT NULL AND v_mensaje IS DISTINCT FROM v_mensaje_usuario THEN
            RAISE EXCEPTION 'La plantilla del detalle no corresponde a la configurada para el emisor' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER emergen_alerta BEFORE INSERT OR UPDATE ON public.alerta
FOR EACH ROW EXECUTE FUNCTION public.emergen_validar_alerta();

CREATE FUNCTION public.emergen_proteger_detalle_historico() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.alerta WHERE detalle_alerta_id = OLD.detalle_alerta_id) THEN
        IF (NEW.msj_personalizado_id IS DISTINCT FROM OLD.msj_personalizado_id AND NEW.msj_personalizado_id IS NOT NULL)
           OR (NEW.antecedente_medico_id IS DISTINCT FROM OLD.antecedente_medico_id AND NEW.antecedente_medico_id IS NOT NULL) THEN
            RAISE EXCEPTION 'No se reemplazan las referencias del detalle histórico; solo se permite retirarlas' USING ERRCODE = '23514';
        END IF;
        IF NEW.texto_mensaje IS DISTINCT FROM OLD.texto_mensaje
           AND NOT (NEW.texto_mensaje = '[Contenido eliminado]' AND NEW.msj_personalizado_id IS NULL AND NEW.antecedente_medico_id IS NULL) THEN
            RAISE EXCEPTION 'El texto histórico es inmutable salvo depuración de datos personales' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER emergen_detalle_historico BEFORE UPDATE ON public.detalle_alerta
