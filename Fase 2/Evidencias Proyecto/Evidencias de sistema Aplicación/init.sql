CREATE FUNCTION public.emergen_validar_envio() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE v_usuario integer;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.alerta_id IS DISTINCT FROM OLD.alerta_id
           OR NEW.tipo_notificacion IS DISTINCT FROM OLD.tipo_notificacion
           OR (NEW.contacto_emergencia_id IS DISTINCT FROM OLD.contacto_emergencia_id AND NEW.contacto_emergencia_id IS NOT NULL) THEN
            RAISE EXCEPTION 'No se reasigna un envío histórico' USING ERRCODE = '23514';
        END IF;
        IF OLD.estado_envio_id <> 1 AND NEW.estado_envio_id <> OLD.estado_envio_id THEN
            RAISE EXCEPTION 'Sin reintentos: un envío terminal no cambia de estado' USING ERRCODE = '23514';
        END IF;
    ELSE
        IF NEW.contacto_emergencia_id IS NULL THEN RAISE EXCEPTION 'Un envío nuevo requiere contacto' USING ERRCODE = '23514'; END IF;
        SELECT usuario_id INTO v_usuario FROM public.alerta WHERE alerta_id = NEW.alerta_id
          AND estado_alerta = CASE WHEN NEW.tipo_notificacion = 'ACTIVACION' THEN 'ACTIVA' ELSE 'FINALIZADA' END FOR UPDATE;
        IF NOT FOUND OR v_usuario IS NULL THEN RAISE EXCEPTION 'El estado de la alerta no permite este tipo de envío' USING ERRCODE = '23514'; END IF;
        IF NOT EXISTS (SELECT 1 FROM public.contacto_emergencia WHERE contacto_emergencia_id = NEW.contacto_emergencia_id AND usuario_id = v_usuario) THEN
            RAISE EXCEPTION 'Contacto ajeno al emisor de la alerta' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER emergen_envio BEFORE INSERT OR UPDATE ON public.envio_alerta
FOR EACH ROW EXECUTE FUNCTION public.emergen_validar_envio();

-- Cada transición real a FINALIZADA confirma su aviso en la misma transacción.
CREATE FUNCTION public.emergen_encolar_finalizacion() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
    INSERT INTO public.envio_alerta(alerta_id, contacto_emergencia_id, tipo_notificacion)
    SELECT NEW.alerta_id, contacto_emergencia_id, 'FINALIZACION'
    FROM public.contacto_emergencia WHERE usuario_id = NEW.usuario_id
    ON CONFLICT (alerta_id, contacto_emergencia_id, tipo_notificacion) DO NOTHING;
    RETURN NEW;
END;
$$;
CREATE TRIGGER emergen_alerta_notifica_cierre AFTER UPDATE OF estado_alerta ON public.alerta
FOR EACH ROW WHEN (OLD.estado_alerta = 'ACTIVA' AND NEW.estado_alerta = 'FINALIZADA' AND NEW.usuario_id IS NOT NULL)
EXECUTE FUNCTION public.emergen_encolar_finalizacion();

CREATE FUNCTION public.emergen_validar_enlace() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
    PERFORM 1 FROM public.alerta WHERE alerta_id = NEW.alerta_id FOR UPDATE;
    IF TG_OP = 'UPDATE' AND NEW.alerta_id IS DISTINCT FROM OLD.alerta_id THEN
        RAISE EXCEPTION 'No se reasigna un enlace médico a otra alerta' USING ERRCODE = '23514';
    END IF;
    IF (TG_OP = 'INSERT' OR NEW.token_hash IS DISTINCT FROM OLD.token_hash OR NEW.fecha_expiracion IS DISTINCT FROM OLD.fecha_expiracion)
       AND NOT EXISTS (SELECT 1 FROM public.alerta WHERE alerta_id = NEW.alerta_id AND estado_alerta = 'ACTIVA' AND usuario_id IS NOT NULL) THEN
        RAISE EXCEPTION 'Solo una alerta activa admite generar o renovar enlace médico' USING ERRCODE = '23514';
    END IF;
    IF NEW.fecha_revocacion IS NULL AND NOT EXISTS (SELECT 1 FROM public.alerta WHERE alerta_id = NEW.alerta_id AND estado_alerta = 'ACTIVA' AND usuario_id IS NOT NULL) THEN
        RAISE EXCEPTION 'No se puede quitar la revocación de un enlace de alerta terminada' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER emergen_enlace BEFORE INSERT OR UPDATE ON public.enlace_medico
FOR EACH ROW EXECUTE FUNCTION public.emergen_validar_enlace();

CREATE FUNCTION public.emergen_revocar_enlace() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
    IF OLD.estado_alerta = 'ACTIVA' AND NEW.estado_alerta <> 'ACTIVA' THEN
        UPDATE public.enlace_medico
        SET fecha_revocacion = COALESCE(fecha_revocacion, GREATEST(clock_timestamp(), fecha_generacion))
        WHERE alerta_id = NEW.alerta_id;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER emergen_alerta_revoca AFTER UPDATE OF estado_alerta ON public.alerta
FOR EACH ROW EXECUTE FUNCTION public.emergen_revocar_enlace();

CREATE FUNCTION public.emergen_comprobar_total_venta(p_id integer) RETURNS void
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE v_total integer; v_suma bigint; v_lineas bigint;
BEGIN
    SELECT total_venta INTO v_total FROM public.venta WHERE venta_id = p_id FOR UPDATE;
    IF NOT FOUND THEN RETURN; END IF;
    SELECT count(*), COALESCE(sum(cantidad::bigint * precio_uni::bigint), 0) INTO v_lineas, v_suma
    FROM public.detalle_venta WHERE venta_id = p_id;
    IF v_lineas = 0 OR v_suma <> v_total THEN
        RAISE EXCEPTION 'Venta %: debe tener detalles y total_venta igual a SUM(cantidad * precio_uni)', p_id USING ERRCODE = '23514';
    END IF;
END;
$$;

CREATE FUNCTION public.emergen_validar_total_venta() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN PERFORM public.emergen_comprobar_total_venta(OLD.venta_id); END IF;
    IF TG_OP <> 'DELETE' THEN PERFORM public.emergen_comprobar_total_venta(NEW.venta_id); END IF;
    RETURN NULL;
END;
$$;
-- Comprobación al COMMIT: permite insertar cabecera y detalle en una transacción.
CREATE CONSTRAINT TRIGGER emergen_venta_total AFTER INSERT OR UPDATE ON public.venta
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.emergen_validar_total_venta();
CREATE CONSTRAINT TRIGGER emergen_detalle_total AFTER INSERT OR UPDATE OR DELETE ON public.detalle_venta
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.emergen_validar_total_venta();

