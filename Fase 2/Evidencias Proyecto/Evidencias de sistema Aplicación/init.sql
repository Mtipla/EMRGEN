CREATE FUNCTION public.emergen_bloquear_usuario(p_id integer) RETURNS void
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
    -- Escritura sin cambio de valor: serializa cupos/contactos del mismo perfil.
    -- La nueva versión de fila también fuerza conflicto de serialización en
    -- REPEATABLE READ/SERIALIZABLE; el backend debe reintentar la transacción.
    UPDATE public.usuario SET nombre_usuario = nombre_usuario WHERE usuario_id = p_id;
END;
$$;

CREATE FUNCTION public.emergen_validar_vinculo() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE v_padre integer; v_capacidad integer; v_ocupados integer;
BEGIN
    IF NEW.usuario_principal_id IS NULL THEN RETURN NEW; END IF;
    IF NEW.usuario_principal_id = NEW.usuario_id THEN
        RAISE EXCEPTION 'Un usuario no puede ser su propio principal' USING ERRCODE = '23514';
    END IF;
    PERFORM public.emergen_bloquear_usuario(NEW.usuario_principal_id);
    SELECT usuario_principal_id INTO v_padre FROM public.usuario WHERE usuario_id = NEW.usuario_principal_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Principal inexistente' USING ERRCODE = '23503'; END IF;
    IF v_padre IS NOT NULL THEN RAISE EXCEPTION 'No se admiten cadenas de apadrinados' USING ERRCODE = '23514'; END IF;
    IF EXISTS (SELECT 1 FROM public.usuario WHERE usuario_principal_id = NEW.usuario_id)
       OR EXISTS (SELECT 1 FROM public.plan_usuario WHERE usuario_id = NEW.usuario_id) THEN
        RAISE EXCEPTION 'Resolver primero los dependientes y el plan propio antes de vincular este perfil' USING ERRCODE = '23514';
    END IF;
    SELECT cupos_apadrinados_adq INTO v_capacidad FROM public.plan_usuario WHERE usuario_id = NEW.usuario_principal_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'El principal no tiene plan/cupos adquiridos' USING ERRCODE = '23514'; END IF;
    SELECT count(*) INTO v_ocupados FROM public.usuario WHERE usuario_principal_id = NEW.usuario_principal_id AND usuario_id <> NEW.usuario_id;
    IF v_ocupados >= LEAST(v_capacidad, 5) THEN
        RAISE EXCEPTION 'Sin cupos disponibles para apadrinados' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER emergen_usuario_vinculo BEFORE INSERT OR UPDATE OF usuario_principal_id ON public.usuario
FOR EACH ROW EXECUTE FUNCTION public.emergen_validar_vinculo();

CREATE FUNCTION public.emergen_proteger_ultimo_admin() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
    IF OLD.rol_id = 1 AND (TG_OP = 'DELETE' OR NEW.rol_id <> 1) THEN
        UPDATE public.rol SET nombre_rol = nombre_rol WHERE rol_id = 1;
        IF (SELECT count(*) FROM public.usuario WHERE rol_id = 1) <= 1 THEN
            RAISE EXCEPTION 'No se puede eliminar ni quitar el rol al último administrador' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER emergen_00_ultimo_admin BEFORE DELETE OR UPDATE OF rol_id ON public.usuario
