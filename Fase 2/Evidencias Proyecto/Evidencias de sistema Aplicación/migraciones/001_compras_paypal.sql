-- Compra de cuentas apadrinadas con PayPal, para una BD creada con un init.sql anterior.
-- init.sql solo corre al crear el volumen; este script lleva una BD existente al mismo
-- esquema. Solo agrega (no borra ni modifica datos) y puede ejecutarse más de una vez.
--
--   Get-Content migraciones/001_compras_paypal.sql | docker exec -i postgres_emergen_db sh -c 'psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB"'

BEGIN;

-- Identity en las PK (el diccionario de datos ya las define así). El contador arranca
-- después del mayor ID existente para no chocar con filas cargadas a mano.
DO $$
DECLARE
  t RECORD;
BEGIN
  FOR t IN SELECT * FROM (VALUES
    ('venta', 'venta_id'),
    ('detalle_venta', 'detalle_venta_id'),
    ('plan_usuario', 'plan_usuario_id')) AS v(tabla, columna)
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_name = t.tabla AND column_name = t.columna AND is_identity = 'YES'
    ) THEN
      EXECUTE format('ALTER TABLE %I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY', t.tabla, t.columna);
      EXECUTE format(
        'SELECT setval(pg_get_serial_sequence(%L, %L), COALESCE(MAX(%I), 0) + 1, false) FROM %I',
        t.tabla, t.columna, t.columna, t.tabla);
    END IF;
  END LOOP;
END $$;

ALTER TABLE venta ADD COLUMN IF NOT EXISTS orden_paypal_id VARCHAR(36);
ALTER TABLE venta ADD COLUMN IF NOT EXISTS captura_paypal_id VARCHAR(36);
ALTER TABLE venta ADD COLUMN IF NOT EXISTS monto_cobrado NUMERIC(10, 2);
ALTER TABLE venta ADD COLUMN IF NOT EXISTS moneda_cobrada CHAR(3);
CREATE UNIQUE INDEX IF NOT EXISTS venta_orden_paypal_id_key ON venta (orden_paypal_id);

-- Falla si un usuario ya tiene dos filas en plan_usuario: unirlas a mano antes de reintentar.
CREATE UNIQUE INDEX IF NOT EXISTS plan_usuario_usuario_id_key ON plan_usuario (usuario_id);

INSERT INTO metodo_pago (metodo_pago_id, nombre_metodo) VALUES
